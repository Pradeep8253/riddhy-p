/**
 * Returns localized category name
 */
export function getLocalizedCategoryName(category, locale = 'en') {
  if (!category) return '';
  const isHi = locale === 'hi';

  if (typeof category === 'object') {
    if (!isHi) return category.name || category.title || category.categoryLabel || category.slug || '';

    // Check if category has native Hindi name
    if (category.name_hi && typeof category.name_hi === 'string' && category.name_hi.trim()) {
      const val = category.name_hi.trim();
      if (val === 'कंबल (द्वि-1)') return 'कंबल (2-इन-1)';
      if (categoryNamesHi[val]) return categoryNamesHi[val];
      if (/[\u0900-\u097F]/.test(val)) return val;
    }

    if (category.name && categoryNamesHi[category.name]) return categoryNamesHi[category.name];
    if (category.slug && categoryNamesHi[category.slug]) return categoryNamesHi[category.slug];
    if (category.categoryLabel && categoryNamesHi[category.categoryLabel]) return categoryNamesHi[category.categoryLabel];

    const strKey = category.name || category.slug || category.categoryLabel || '';
    const norm = strKey.toLowerCase().trim();
    if (categoryNamesHi[norm]) return categoryNamesHi[norm];

    for (const [k, v] of Object.entries(categoryNamesHi)) {
      if (k.toLowerCase() === norm) return v;
    }

    // Try without parentheses
    const stripped = norm.replace(/\s*\([^)]*\)/g, '').trim();
    if (stripped && categoryNamesHi[stripped]) return categoryNamesHi[stripped];

    return category.name || strKey;
  }

  // String input
  const str = String(category).trim();
  if (!isHi) return str;
  if (categoryNamesHi[str]) return categoryNamesHi[str];

  const norm = str.toLowerCase();
  if (categoryNamesHi[norm]) return categoryNamesHi[norm];

  for (const [k, v] of Object.entries(categoryNamesHi)) {
    if (k.toLowerCase() === norm) return v;
  }

  const stripped = norm.replace(/\s*\([^)]*\)/g, '').trim();
  if (stripped && categoryNamesHi[stripped]) return categoryNamesHi[stripped];

  return str;
}

