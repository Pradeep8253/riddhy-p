export function getLocalizedBrand(brand, locale = 'en') {
  if (!brand) return '';
  if (locale !== 'hi') return String(brand);
  const trimmed = String(brand).trim();
  if (!trimmed) return '';
  if (/[\u0900-\u097F]/.test(trimmed)) return trimmed;
  if (brandNamesHi[trimmed]) return brandNamesHi[trimmed];
  const lower = trimmed.toLowerCase();
  for (const [key, value] of Object.entries(brandNamesHi)) {
    if (key.toLowerCase() === lower) return value;
  }
  return trimmed;
}
