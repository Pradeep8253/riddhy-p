/**
 * Returns localized product name
 */
export function getLocalizedProductName(product, locale = 'en') {
  if (locale !== 'hi' || !product) return product?.name || '';
  if (product.name_hi && typeof product.name_hi === 'string' && product.name_hi.trim() && /[\u0900-\u097F]/.test(product.name_hi)) {
    return product.name_hi;
  }
  if (product.name && productNamesHi[product.name]) return productNamesHi[product.name];
  if (product.slug && productNamesHi[product.slug]) return productNamesHi[product.slug];

  const normName = (product.name || '').toLowerCase().trim();
  const normSlug = (product.slug || '').toLowerCase().trim();
  for (const [k, v] of Object.entries(productNamesHi)) {
    const kNorm = k.toLowerCase().trim();
    if (kNorm === normName || kNorm === normSlug) return v;
  }

  // Fallback: smart keyword localization
  let translated = product.name || '';
  for (const [pattern, replacement] of COMMON_WORD_MAP) {
    translated = translated.replace(pattern, replacement);
  }
  return translated;
}

