export function getLocalizedBadge(badgeText, locale = 'en') {
  if (locale !== 'hi' || !badgeText) return badgeText || '';
  if (badgeNamesHi[badgeText]) return badgeNamesHi[badgeText];
  const norm = String(badgeText).toLowerCase().trim();
  if (badgeNamesHi[norm]) return badgeNamesHi[norm];
  if (/only\s+(\d+)\s+left/i.test(badgeText)) {
    const num = badgeText.match(/\d+/)?.[0] || '';
    return `केवल ${num} शेष`;
  }
  return badgeText;
}

