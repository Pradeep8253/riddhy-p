export function tr(locale, key) {
  // Support both tr(key) and tr(locale, key)
  const actualKey = key || locale;
  const lang = (key && locale && messages[locale]) ? locale : 'en';
  return (messages[lang] && messages[lang][actualKey]) || messages.en[actualKey] || actualKey;
}

export function getSavedLocale() {
  if (typeof document !== 'undefined') {
    const local = window.localStorage.getItem('rf-locale');
    if (local === 'hi' || local === 'en') return local;
  }
  return "en";
}

export function setSavedLocale(code = 'en') {
  if (typeof document !== "undefined") {
    document.cookie = `rf_locale=${code}; path=/; max-age=31536000; SameSite=Lax`;
    document.cookie = `rf-locale=${code}; path=/; max-age=31536000; SameSite=Lax`;
    try {
      window.localStorage.setItem('rf-locale', code);
    } catch {}
  }
}
