export function tr(locale, key) {
  return messages[locale]?.[key] || messages.en[key] || key;
}

export function getSavedLocale() {
  if (typeof document === 'undefined') return 'en';
  const match = document.cookie.match(/(?:^|;\s*)rf_locale=([^;]+)/);
  return match && ['en', 'hi'].includes(match[1]) ? match[1] : 'en';
}

export function setSavedLocale(locale) {
  if (typeof document !== 'undefined') {
    const val = locale === 'hi' ? 'hi' : 'en';
    document.cookie = `rf_locale=${val}; path=/; max-age=31536000; SameSite=Lax`;
  }
}
